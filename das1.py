
season = int(input("1-Хавар, 2-Зун, 3-Намар, 4-Өвөл: "))

if season == 1:
    print("Хавар болж цэцэгс цэцэглэлээ.")
if season == 2:
    print("Зун болж халуун боллоо.")
if season == 3:
    print("Намар болж навч уналаа.")
if season == 4:
    print("Өвөл болж цас орлоо.")
else:
    print("Буруу утга оруулсан байна. 1-4 хооронд тоон утга оруулна уу.")